export const DICTS: Record<Lang, Record<Key, Entry>> = { el: el as Record<Key, Entry>, en };

let current: Lang = 'el';

export function resolveLang(pref: 'auto' | Lang, languages: readonly string[] = navigator.languages ?? []): Lang {
  if (pref !== 'auto') return pref;
  return languages.some((l) => l.toLowerCase().startsWith('el')) ? 'el' : 'en';
}

export function setLang(l: Lang) {
  current = l;
  document.documentElement.lang = l;
  document.title = `${DICTS[l].title as string} · ${DICTS[l].subtitle as string}`;
}

export const getLang = () => current;

export function t(key: Key, vars: Vars = {}): string {
  const e = DICTS[current][key] ?? DICTS.el[key];
  return typeof e === 'function' ? e(vars) : e;
}

/** Κείμενο από τους καταλόγους (μετοχές, αντικείμενα, ειδήσεις). */
export const tr = (x: Tr) => x[current];

const nf = new Map<string, Intl.NumberFormat>();
function fmt(key: string, opts: Intl.NumberFormatOptions) {
  const k = `${current}|${key}`;
  if (!nf.has(k)) nf.set(k, new Intl.NumberFormat(current === 'el' ? 'el-GR' : 'en-US', opts));
  return nf.get(k)!;
}

/** Χρήματα χωρίς δεκαδικά: $12.345 / $12,345. */
export const money = (x: number) => (x < 0 ? '−' : '') + '$' + fmt('m', { maximumFractionDigits: 0 }).format(Math.abs(x));
/** Χρήματα με πρόσημο: +$120 / −$40. */
export const signed = (x: number) => (x >= 0 ? '+' : '') + money(x);
/** Τιμή μετοχής με 2 δεκαδικά. */
export const price = (x: number) => fmt('p', { minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(x);
/** Ποσοστό με πρόσημο: +3,4%. */
export const pct = (x: number) =>
  (x >= 0 ? '+' : '−') + fmt('pc', { minimumFractionDigits: 1, maximumFractionDigits: 1 }).format(Math.abs(x * 100)) + '%';
